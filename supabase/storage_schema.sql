-- Run once in the Supabase SQL editor. Nothing reads or alters auth.users.
-- Application tables are in a private schema, outside the public Data API.
-- Paste/run the ENTIRE file. RLS is explicitly enabled below; no editor injection needed.
BEGIN;
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;
CREATE SCHEMA IF NOT EXISTS verifier;
REVOKE ALL ON SCHEMA verifier FROM PUBLIC, anon, authenticated;
CREATE TABLE IF NOT EXISTS verifier.schema_version(id integer PRIMARY KEY CHECK(id=1), version integer NOT NULL);
INSERT INTO verifier.schema_version VALUES(1,1) ON CONFLICT(id) DO NOTHING;
CREATE TABLE IF NOT EXISTS verifier.workspaces(id text PRIMARY KEY, name text NOT NULL);
CREATE TABLE IF NOT EXISTS verifier.members(principal text NOT NULL, workspace text NOT NULL REFERENCES verifier.workspaces(id), PRIMARY KEY(principal,workspace));
CREATE TABLE IF NOT EXISTS verifier.documents(id text PRIMARY KEY, workspace text NOT NULL REFERENCES verifier.workspaces(id), name text NOT NULL, sha text NOT NULL, status text NOT NULL, metadata text NOT NULL DEFAULT '{}', context text NOT NULL DEFAULT '{}', created double precision NOT NULL, UNIQUE(workspace,sha));
CREATE UNIQUE INDEX IF NOT EXISTS documents_workspace_id ON verifier.documents(workspace,id);
CREATE TABLE IF NOT EXISTS verifier.jobs(id text PRIMARY KEY, workspace text NOT NULL REFERENCES verifier.workspaces(id), principal text NOT NULL, kind text NOT NULL, payload text NOT NULL, status text NOT NULL, stage text NOT NULL, result text NOT NULL DEFAULT '{}', checkpoint text NOT NULL DEFAULT '{}', attempts integer NOT NULL DEFAULT 0, created double precision NOT NULL, updated double precision NOT NULL, run_token text);
CREATE INDEX IF NOT EXISTS jobs_workspace_created ON verifier.jobs(workspace,created DESC);
CREATE INDEX IF NOT EXISTS jobs_queue ON verifier.jobs(status,created);
CREATE TABLE IF NOT EXISTS verifier.decisions(job text NOT NULL REFERENCES verifier.jobs(id), atom integer NOT NULL, decision text NOT NULL, note text NOT NULL, reviewer text NOT NULL, updated double precision NOT NULL, PRIMARY KEY(job,atom));
CREATE TABLE IF NOT EXISTS verifier.decision_events(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job text NOT NULL, atom integer NOT NULL, decision text NOT NULL, note text NOT NULL, reviewer text NOT NULL, updated double precision NOT NULL);
CREATE TABLE IF NOT EXISTS verifier.worker_status(id integer PRIMARY KEY CHECK(id=1), heartbeat double precision NOT NULL);
CREATE TABLE IF NOT EXISTS verifier.model_connections(principal text PRIMARY KEY, version text NOT NULL UNIQUE, secret text NOT NULL, models text NOT NULL, updated double precision NOT NULL);
CREATE TABLE IF NOT EXISTS verifier.artifacts(workspace text NOT NULL REFERENCES verifier.workspaces(id), document_id text, path text NOT NULL, object_key text NOT NULL, sha text NOT NULL, size bigint NOT NULL, PRIMARY KEY(workspace,path), FOREIGN KEY(workspace,document_id) REFERENCES verifier.documents(workspace,id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS verifier.vector_collections(workspace text NOT NULL REFERENCES verifier.workspaces(id), name text NOT NULL, model text NOT NULL, dimensions integer NOT NULL CHECK(dimensions=768), PRIMARY KEY(workspace,name));
CREATE TABLE IF NOT EXISTS verifier.vectors(workspace text NOT NULL, collection text NOT NULL, id text NOT NULL, document_id text NOT NULL, embedding extensions.vector(768) NOT NULL, document text NOT NULL, metadata text NOT NULL, PRIMARY KEY(workspace,collection,id), FOREIGN KEY(workspace,collection) REFERENCES verifier.vector_collections(workspace,name), FOREIGN KEY(workspace,document_id) REFERENCES verifier.documents(workspace,id) ON DELETE CASCADE);
CREATE INDEX IF NOT EXISTS vectors_document ON verifier.vectors(workspace,collection,document_id);
-- Exact cosine search initially: no approximate-index recall changes for the beta.

ALTER TABLE verifier.schema_version ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.workspaces ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.decisions ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.decision_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.worker_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.model_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.artifacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.vector_collections ENABLE ROW LEVEL SECURITY;
ALTER TABLE verifier.vectors ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE verifier.schema_version, verifier.workspaces, verifier.members,
  verifier.documents, verifier.jobs, verifier.decisions, verifier.decision_events,
  verifier.worker_status, verifier.model_connections, verifier.artifacts,
  verifier.vector_collections, verifier.vectors FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA verifier FROM PUBLIC, anon, authenticated;

-- Server secret/service role can access objects; browser roles receive no policy.
INSERT INTO storage.buckets(id,name,public,file_size_limit)
VALUES('verifier-private','verifier-private',false,52428800)
ON CONFLICT(id) DO NOTHING;
-- Fail if an existing bucket with this name was made public.
DO $$ BEGIN
  IF (SELECT public FROM storage.buckets WHERE id='verifier-private') THEN
    RAISE EXCEPTION 'verifier-private must be private';
  END IF;
END $$;
-- Restrictive policy also defeats an unrelated, broad permissive bucket policy.
-- Browser requests use the application authorization gate, never this bucket API.
DROP POLICY IF EXISTS verifier_private_server_only ON storage.objects;
CREATE POLICY verifier_private_server_only ON storage.objects AS RESTRICTIVE
FOR ALL TO anon, authenticated
USING (bucket_id <> 'verifier-private')
WITH CHECK (bucket_id <> 'verifier-private');
COMMIT;
